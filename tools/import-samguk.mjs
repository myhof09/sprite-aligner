// Bundle samguk-td's skill recipes (../../samguk-td/art/fx-recipes, written by its scripts/fx-recipes.ts) into the
// gallery as the "삼국지 TD" category: js/safx-samguk.js. Run again whenever those recipes change.
// Each recipe also goes into its element / type categories (화염, 전기, 투사체 …), guessed from its layers, palette and name.
//   node tools/import-samguk.mjs [path to art/fx-recipes]
import { readFileSync, writeFileSync } from 'node:fs';

const dir = new URL(process.argv[2] ? `file:///${process.argv[2].replace(/\\/g, '/').replace(/\/?$/, '/')}` : '../../../samguk-td/art/fx-recipes/', import.meta.url);
const index = JSON.parse(readFileSync(new URL('index.json', dir), 'utf8'));
/** Search tags from what the recipe draws. */
const TYPE_TAG = { slash: '베기', line: '직선', ring: '충격파', sparks: '불꽃', lightning: '번개', glow: '빛', flash: '섬광', smoke: '연기', image: '그림' };

/** samguk-td's element palettes (scripts/fx-recipes.ts PAL), by their darkest color. */
const ELEMENT = { '#5a0e08': '화염', '#1c2a6e': '전기', '#16380f': '독·산', '#0c3a4a': '얼음', '#0b0b10': '먹·책략' };

/** Element / type categories of a recipe (besides 삼국지 TD). label = "장수 · 스킬": names are matched on the skill part. */
function categories(r, label) {
  const name = label.split('·').slice(1).join('·') || label;
  const L = r.layers, has = (t) => L.some((l) => l.type === t), cats = new Set();
  const flash = L.find((l) => l.type === 'flash'), rings = L.filter((l) => l.type === 'ring'), lines = L.filter((l) => l.type === 'line');
  const shot = /화살|총|포|궁|사격|일제|연사|화차|연노|비도|탄/.test(name);
  // what it draws
  if (has('slash')) cats.add('베기');
  if (shot) cats.add('투사체');
  else if (lines.length && !has('slash')) cats.add(lines.some((l) => (l.count ?? 1) >= 3 && l.jitter) ? '바람' : '찌르기');
  if (has('lightning') && !L.some((l) => l.type === 'lightning' && l.palette)) cats.add('전기');
  if (flash && flash.shape === 'star' && flash.points >= 7 && has('glow')) cats.add('폭발');
  if (flash && has('sparks') && !has('slash') && !lines.length && !has('smoke') && rings.every((l) => !l.gaps) && ['star', 'circle'].includes(flash.shape)) cats.add('타격·둔기');
  if (rings.some((l) => (l.aspect ?? 1) <= 0.45 && !l.gaps) && has('smoke')) cats.add('땅·바위');
  if (rings.some((l) => (l.gaps ?? 0) >= 4) && flash && flash.shape === 'diamond') cats.add('먹·책략');
  if (rings.some((l) => (l.aspect ?? 1) < 0.4 && l.gaps) && L.some((l) => l.type === 'sparks' && l.stream)) cats.add('버프·디버프');
  if (rings.length === 1 && flash && L.length === 2 && !has('sparks')) cats.add('상태이상');
  if (has('smoke') && L.every((l) => l.type === 'smoke' || l.type === 'sparks')) cats.add('연기·먼지');
  // element palettes
  const el = ELEMENT[(r.palette || [])[0]];
  if (el) cats.add(el);
  // names
  if (/치유|복숭아|회복|부활|흙인형/.test(name)) cats.add('빛·치유');
  if (/안개|격노/.test(name)) cats.add('어둠');
  if (/형제|부활|흙인형|분열/.test(name)) cats.add('소환·순간이동');
  if (/표시|봉인|팔괘|팔진|책략|계략|맹약/.test(name)) cats.add('먹·책략');
  if (/둔화|빙결|기절|파갑|침묵/.test(name)) cats.add('상태이상');
  if (/군령|호령|독전|인덕|왕좌|괄목|군량|효용|風|林/.test(name)) cats.add('버프·디버프');
  if (/불길|화공|화계|화염|火/.test(name)) cats.add('화염');
  if (/모래|먼지|무너짐|연막/.test(name)) cats.add('연기·먼지');
  if (/돌진|돌격|기병|철기|백마의종/.test(name)) cats.add('바람');
  if (!cats.size) cats.add('기타');
  return [...cats];
}

const list = index.filter((e) => { try { readFileSync(new URL(e.file, dir)); return true; } catch { console.warn('missing', e.file); return false; } }).map((e) => {
  const r = JSON.parse(readFileSync(new URL(e.file, dir), 'utf8'));
  const sub = e.group.split('·').pop().trim();   // 장수 / 무기 각성 / 조합 / 보스
  const tags = [...new Set([sub, ...r.layers.map((l) => TYPE_TAG[l.type]).filter(Boolean)])];
  return { key: 'samguk:' + e.key, label: e.label, recipe: { ...r, name: e.label, category: ['삼국지 TD', ...categories(r, e.label)], tags } };
});
writeFileSync(new URL('../js/safx-samguk.js', import.meta.url),
  `// safx-samguk.js — the skill effects of 삼국지 TD (samguk-td art/fx-recipes, our own designs), generated by
// tools/import-samguk.mjs: do not edit by hand.
'use strict';
const SAFX_SAMGUK = ${JSON.stringify(list)};
`);
const count = {};
for (const x of list) for (const c of x.recipe.category.slice(1)) count[c] = (count[c] ?? 0) + 1;
console.log(`${list.length} recipes -> js/safx-samguk.js`, JSON.stringify(count));
